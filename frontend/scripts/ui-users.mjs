import { chromium } from 'playwright-core';
const base = 'http://localhost:5180';
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
await page.goto(base + '/login', { waitUntil: 'networkidle' });
await page.fill('input[type=email]', 'admin@kdshop.dev');
await page.fill('input[type=password]', 'Demo@123456');
await page.click('button.submit');
await page.waitForTimeout(1800);
await page.goto(base + '/admin/users', { waitUntil: 'networkidle' });
await page.waitForTimeout(1300);
await page.screenshot({ path: 'D:/web-ai-code/KDShop/.shots/admin-users.png' });
await page.getByRole('button', { name: '角色' }).first().click();
await page.waitForTimeout(600);
await page.screenshot({ path: 'D:/web-ai-code/KDShop/.shots/admin-roles.png' });
console.log('ok');
await browser.close();
