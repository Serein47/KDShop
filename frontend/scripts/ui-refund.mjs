import { chromium } from 'playwright-core';
const base = 'http://localhost:5180';
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
await page.goto(base + '/login', { waitUntil: 'networkidle' });
await page.fill('input[type=email]', 'merchant1@kdshop.dev');
await page.fill('input[type=password]', 'Demo@123456');
await page.click('button.submit');
await page.waitForTimeout(1800);
await page.goto(base + '/merchant/refunds', { waitUntil: 'networkidle' });
await page.waitForTimeout(1400);
console.log('merchant:', (await page.locator('body').innerText()).replace(/\n+/g, ' | ').slice(0, 220));
await page.screenshot({ path: 'D:/web-ai-code/KDShop/.shots/merchant-refunds.png' });
await browser.close();
