import { chromium } from 'playwright-core';
const base = 'http://localhost:5180';
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
await page.goto(base + '/login', { waitUntil: 'networkidle' });
await page.fill('input[type=email]', 'customer@kdshop.dev');
await page.fill('input[type=password]', 'Demo@123456');
await page.click('button.submit');
await page.waitForTimeout(2000);
await page.goto(base + '/account', { waitUntil: 'networkidle' });
await page.waitForTimeout(1500);
const badge = await page.locator('.cart-badge').innerText().catch(() => 'none');
console.log('badge:', badge);
console.log('account:', (await page.locator('body').innerText()).replace(/\n+/g, ' | ').slice(0, 220));
await page.screenshot({ path: 'D:/web-ai-code/KDShop/.shots/account.png' });
await page.goto(base + '/help', { waitUntil: 'networkidle' });
await page.waitForTimeout(1000);
await page.screenshot({ path: 'D:/web-ai-code/KDShop/.shots/help.png' });
await browser.close();
