import { chromium } from 'playwright-core';
const base = 'http://localhost:5180';
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
await page.goto(base + '/login', { waitUntil: 'networkidle' });
await page.click('button.submit');
await page.waitForTimeout(1500);
await page.goto(base + '/checkout', { waitUntil: 'networkidle' });
await page.waitForTimeout(1500);
await page.locator('.submit').click();
await page.waitForTimeout(2000);
console.log('after submit:', page.url());
await page.getByRole('button', { name: '去支付' }).click();
await page.waitForTimeout(2500);
console.log('pay page:', page.url());
await page.getByRole('button', { name: '模拟支付成功' }).click();
await page.waitForTimeout(2000);
console.log('state:', await page.locator('.state').innerText().catch(() => 'none'));
await page.screenshot({ path: 'D:/web-ai-code/KDShop/.shots/mock-pay.png' });
await browser.close();
